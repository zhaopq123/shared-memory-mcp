"""shared-memory-mcp —— 多 agent 共享记忆服务。

━━━ 它解决什么 ━━━

**跨会话失忆 + 多 agent 各记各的。** 一个常驻的 MCP 服务，所有 agent
（DSH / 豆包 / 任何支持 MCP 的工具）连同一个地址，读写同一份记忆。

━━━ 设计取向（刻意如此）━━━

· **不做 agent 隔离** —— 没有 per-agent 命名空间。所有 agent 共享一个池子，
  谁写谁读互相可见。这不是疏忽，是需求。
· **一条记忆 = 一个 Markdown 文件** —— 纯文本、人可读、可手改、可 diff。
· **整个 vault 是 git 仓库** —— 版本化 + 可回滚 + 可异地备份。
· **写入串行（单写者 FIFO 队列）** —— 并发不丢数据、不静默覆盖、不会死锁。
· **存储层不碰 LLM** —— 零 API key、零网络依赖。存什么由 agent 决定。
"""

